#!/usr/bin/env python3
"""Write src/quickjs_ng.cppm and src/inline.cpp from quickjs.h.

src/quickjs_ng.cppm exports every type, enumerator of a named enum and
JS_EXTERN function of quickjs.h by `export using` (the upstream globals,
unchanged), and declares the adaptations of its `static inline` API.

A `static inline` function has internal linkage and cannot be exported. Each
public one (JS_NewInt32, JS_IsException, JS_ToCString …) is adapted as a
function of the same name and signature in namespace mcpplibs::mwrap::quickjs_ng,
defined out of line in src/inline.cpp by calling upstream's own inline body:
the same result on every target, one call more.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import fetch, surface  # noqa: E402

HEADER = '''// Generated by tools/gen_exports.py from quickjs.h (QuickJS-ng 0.17.0) — do
// not edit by hand.
//
// mcpplibs.mwrap.quickjs_ng — QuickJS-ng, the embeddable JavaScript engine, as a
// C++ module. Every exported name is the upstream global of <quickjs.h>,
// unchanged; the root also re-exports the macro mappings. The engine is
// compat.quickjs-ng, built from the same release.
//
// The `static inline` API (internal linkage, not exportable) is adapted in
// namespace mcpplibs::mwrap::quickjs_ng under the same names and signatures,
// each calling upstream's inline body (src/inline.cpp).
module;
#include <quickjs.h>

export module mcpplibs.mwrap.quickjs_ng;

export import mcpplibs.mwrap.quickjs_ng.macros;
'''


def render(sf):
    out = [HEADER]
    out.append(f'// types ({len(sf.types)})')
    out += [f'export using ::{n};' for n in sf.types]
    out.append(f'\n// enumerators of the named enums ({len(sf.enumerators)})')
    out += [f'export using ::{n};' for n in sf.enumerators]
    out.append(f'\n// functions ({len(sf.functions)})')
    out += [f'export using ::{n};' for n in sf.functions]
    out.append(f'\n// the static inline API ({len(sf.inlines)}), adapted')
    out.append('export namespace mcpplibs::mwrap::quickjs_ng {')
    out += [f'{i.returns} {i.name}({i.params});' for i in sf.inlines]
    out.append('}  // namespace mcpplibs::mwrap::quickjs_ng\n')
    cppm = '\n'.join(out)

    impl = ['// Generated by tools/gen_exports.py from quickjs.h — do not edit by hand.',
            '//',
            "// The adaptations of quickjs.h's static inline API: each calls upstream's",
            '// own inline body.',
            'module;',
            '#include <quickjs.h>',
            '',
            'module mcpplibs.mwrap.quickjs_ng;',
            '',
            'namespace mcpplibs::mwrap::quickjs_ng {',
            '']
    for i in sf.inlines:
        call = f'::{i.name}({", ".join(i.args)})'
        body = f'return {call};' if i.returns != 'void' else f'{call};'
        impl.append(f'{i.returns} {i.name}({i.params}) {{ {body} }}')
    impl += ['', '}  // namespace mcpplibs::mwrap::quickjs_ng', '']
    return cppm, '\n'.join(impl)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    cppm, impl = render(surface(fetch(root) / 'quickjs.h'))
    stale = []
    for path, text in ((root / 'src/quickjs_ng.cppm', cppm), (root / 'src/inline.cpp', impl)):
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(root).as_posix())
        else:
            path.write_text(text, encoding='utf-8')
            print('wrote', path.relative_to(root).as_posix())
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
